export function localQuestion(settings, index) {
  const roleQuestions = ROLE_QUESTIONS[settings.role] || [];
  const sequence = [...BASE];
  if (roleQuestions.length) {
    const roleItems = roleQuestions.map((text) => ({ text, focus: "技术考察" }));
    sequence.splice(2, 0, ...roleItems);
  }
  const template = sequence[Math.min(index, sequence.length - 1)];
  const project = projectContext(settings);
  let text = template.text;
  const opening = STYLE_OPENERS[settings.style] || "";
  if (opening && template.focus !== "反问环节") {
    text = `${opening}${text}`;
  }
  if (template.focus === "项目深挖" && project) {
    text = `${opening}你简历中提到：${project}。请从这里面挑一个你最有代表性的项目，用 STAR 讲清楚背景、任务、行动和结果，并说明你的个人贡献与量化成果。`;
  } else if (template.focus === "岗位匹配" && project) {
    text = `${opening}对照这份 JD，结合你简历里的项目经历（例如 ${project.slice(0, 120)}…），说明你哪三项能力最匹配，以及还有哪些差距。`;
  }
  return {
    text,
    focus: template.focus || "综合考察",
    source: "offline"
  };
}
