function projectContext(settings = {}) {
  const analysis = settings.resumeAnalysis;
  if (analysis?.projects?.length) {
    const first = analysis.projects[0];
    return `${first.title || "项目"}：${first.detail || first.tech || ""}`.slice(0, 260);
  }
  const lines = (settings.resume || "")
    .split(/\n+/)
    .map((line) => line.trim())
    .filter(Boolean);
  const start = lines.findIndex((line) => /项目|经历|作品|负责|开发|系统/.test(line));
  if (start < 0) return "";
  return lines.slice(Math.max(0, start - 1), start + 6).join(" / ").slice(0, 260);
}

